#!/usr/bin/env python3
"""Packs data/*.json + employees.csv into js/seed.js (window.SEED).

Why: the portal then works from any static host AND when index.html is simply double-clicked
(browsers block fetch() of local JSON files). Re-run after editing anything in data/.
"""
import csv, json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
D = os.path.join(ROOT, "data")
load = lambda n: json.load(open(os.path.join(D, n), encoding="utf-8"))

employees = list(csv.DictReader(open(os.path.join(D, "employees.csv"), encoding="utf-8")))
tpl = load("mail_templates.json")

seed = {
    "employees": employees,
    "questions": load("questionnaire.json"),
    "assets": load("assets.json"),
    "submissions": load("submissions.json"),
    "mailLog": load("mail_seed.json"),
    "taxonomy": load("taxonomy.json"),
    "templates": tpl["templates"],
    "settings": {
        "leadDays": 60,                # auto-mail this many days before superannuation
        "portalUrl": "https://YOUR-USER.github.io/smriti-portal/",
        "mailChannel": "demo",         # demo | github | mailto
        "gh": {"repo": "", "branch": "main", "workflow": "reminders.yml"},
        "modes": ["Written questionnaire", "Interview (in person)", "Interview (video call)", "Audio note"],
        "interviewModes": ["Interview (in person)", "Interview (video call)", "Audio note"],
    },
    # DEMO ACCOUNTS ONLY. Replace with Active Directory / OIDC (see README). Password hashes are
    # computed in the browser by js/util.js (U.hash); plain text here is for the demo login sheet.
    "demoUsers": [
        {"username": "admin",   "password": "admin123", "role": "admin",   "name": "Knowledge Admin"},
        {"username": "learner", "password": "learn123", "role": "learner", "name": "Aarav (Learner)"},
    ],
    "employeePassword": "retire123",
}

with open(os.path.join(ROOT, "js", "seed.js"), "w", encoding="utf-8") as f:
    f.write("/* GENERATED by scripts/build_seed.py: do not edit by hand */\n")
    f.write("window.SEED = " + json.dumps(seed, ensure_ascii=False) + ";\n")
print("js/seed.js written:", len(employees), "employees,", len(seed["assets"]), "assets")
